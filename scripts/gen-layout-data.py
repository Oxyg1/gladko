#!/usr/bin/env python3
"""Generates src/layout-data.js: word lists and letter-bigram statistics for the wrong-keyboard-layout
detector (Russian <-> English).

Requires: pip install wordfreq==3.1.1
Run:      python3 scripts/gen-layout-data.py

The output is data derived from wordfreq (https://github.com/rspeer/wordfreq), whose data files are
licensed under CC BY-SA 4.0; so src/layout-data.js is distributed under CC BY-SA 4.0 as well
(see THIRD_PARTY_LICENSES.md). The build does not run this script; its output is committed.
"""
import json
import math
import os
import re
from collections import defaultdict

from wordfreq import top_n_list, word_frequency

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORDS_IN_LIST = 10000     # shipped word list size per language
WORDS_FOR_BIGRAMS = 60000  # words used to estimate letter statistics
LANGS = {
    "ru": re.compile(r"^[а-яё]+$"),
    "en": re.compile(r"^[a-z]+(?:'[a-z]+)?$"),
}


def build(lang, pattern):
    words = [w for w in top_n_list(lang, WORDS_FOR_BIGRAMS * 2) if pattern.match(w)]
    shipped = [w for w in words if len(w) >= 2][:WORDS_IN_LIST]
    counts = defaultdict(lambda: defaultdict(float))
    for w in words[:WORDS_FOR_BIGRAMS]:
        weight = math.sqrt(word_frequency(w, lang)) or 1e-9
        seq = "^" + w + "$"
        for a, b in zip(seq, seq[1:]):
            counts[a][b] += weight
    alphabet = sorted({c for a in counts for c in counts[a]} | set(counts))
    bigrams = {}
    for a, row in counts.items():
        total = sum(row.values())
        k = total * 0.001  # light smoothing
        denom = total + k * len(alphabet)
        for b, c in row.items():
            bigrams[a + b] = round(math.log((c + k) / denom), 1)
    floor = round(min(bigrams.values()) - 1.0, 1)
    return {"words": "\n".join(shipped), "bigrams": bigrams, "floor": floor}


def main():
    data = {lang: build(lang, pat) for lang, pat in LANGS.items()}
    out = os.path.join(ROOT, "src", "layout-data.js")
    header = (
        "// Generated by scripts/gen-layout-data.py from wordfreq 3.1.1 data. Do not edit by hand.\n"
        "// License: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/), derived from wordfreq\n"
        "// by Robyn Speer (https://github.com/rspeer/wordfreq). See THIRD_PARTY_LICENSES.md.\n"
        "// Contents: the most frequent Russian and English words and letter-bigram log-probabilities,\n"
        "// used only to detect text typed in the wrong keyboard layout.\n"
    )
    with open(out, "w", encoding="utf-8") as f:
        f.write(header)
        f.write("globalThis.GladkoLayoutData = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print("written", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
